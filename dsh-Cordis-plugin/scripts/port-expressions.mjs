// Ports GrokBot's expression_data.dart (25 expressions x 2 eyes x 48-point
// rings) into src/client/data/expressions.ts. Pure mechanical conversion:
// every `Offset(x, y)` is extracted in source order and rechunked, so the
// output is faithful to the Dart constant as long as the count checks out.
//
//   node scripts/port-expressions.mjs [path/to/expression_data.dart]

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const DEFAULT_SOURCE = 'C:/Users/yyt0111/Downloads/GrokBot-master/lib/src/data/expression_data.dart'
const HERE = dirname(fileURLToPath(import.meta.url))

const sourcePath = process.argv[2] ?? DEFAULT_SOURCE
const outPath = resolve(HERE, '../src/client/data/expressions.ts')

const RING_POINTS = 48
const EYES = 2
const EXPRESSIONS = 25
const EXPECTED = EXPRESSIONS * EYES * RING_POINTS

const source = await readFile(sourcePath, 'utf8')
const points = []
const re = /Offset\(\s*([0-9.]+)\s*,\s*([0-9.]+)\s*\)/g
let match
while ((match = re.exec(source)) !== null) {
  points.push([Number(match[1]), Number(match[2])])
}
if (points.length !== EXPECTED) {
  console.error(`expected ${EXPECTED} offsets (${EXPRESSIONS} expressions x ${EYES} eyes x ${RING_POINTS} points), found ${points.length}`)
  process.exit(1)
}

const expressions = []
for (let e = 0; e < EXPRESSIONS; e += 1) {
  const base = e * EYES * RING_POINTS
  expressions.push([
    points.slice(base, base + RING_POINTS),
    points.slice(base + RING_POINTS, base + EYES * RING_POINTS),
  ])
}

const fmtRing = ring => `[\n${ring.map(([x, y]) => `  [${x}, ${y}],`).join('\n')}\n]`
const body = expressions
  .map(([left, right]) => `  [\n${fmtRing(left)},\n${fmtRing(right)},\n  ],`)
  .join('\n')

const out = `/**
 * Generated by scripts/port-expressions.mjs from GrokBot's
 * expression_data.dart (nasawz/GrokBot, BSD-3-Clause). Do not edit by hand.
 *
 * 25 expressions, each two eyes of 48-point closed rings, in the shared
 * 259-unit view box (grokBotViewBoxSize in geometry.ts).
 */

export type Point = readonly [x: number, y: number]

export type EyeRing = readonly Point[]

export type ExpressionRings = readonly [left: EyeRing, right: EyeRing]

export const EXPRESSION_COUNT = ${EXPRESSIONS}
export const RING_POINTS = ${RING_POINTS}

export const grokbotExpressions: readonly ExpressionRings[] = [
${body}
]
`

await mkdir(dirname(outPath), { recursive: true })
await writeFile(outPath, out, 'utf8')
console.log(`wrote ${outPath}: ${expressions.length} expressions x ${RING_POINTS} points per eye`)
